// Date-seeded random picker: stable for the day, changes at midnight
export function dateSeedPick(arr, salt = '') {
  if (!arr || arr.length === 0) return '';
  const today = new Date();
  const seed = today.getFullYear() * 10000 + (today.getMonth() + 1) * 100 + today.getDate();
  let hash = seed;
  for (let i = 0; i < salt.length; i++) hash = ((hash << 5) - hash + salt.charCodeAt(i)) | 0;
  return arr[Math.abs(hash) % arr.length];
}
