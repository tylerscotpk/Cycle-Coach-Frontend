/**
 * Get a fact that hasn't been shown recently (uses localStorage to track)
 * @param {string} phase - Current cycle phase
 * @returns {Object} Fact object
 */
export const getUnseenFact = (phase) => {
  const phaseMap = {
    'Menstrual': 'Menstrual',
    'Follicular': 'Follicular',
    'Ovulation': 'Ovulation',
    'Early Luteal': 'Early Luteal',
    'Late Luteal': 'Late Luteal/PMS',
    'Late Luteal/PMS': 'Late Luteal/PMS',
    'PMS': 'Late Luteal/PMS'
  };

  const mappedPhase = phaseMap[phase] || 'General';
  const facts = CYCLE_FACTS[mappedPhase] || CYCLE_FACTS.General;
  
  // Get seen facts from localStorage
  const seenKey = `cyclecoach_seen_facts_${mappedPhase}`;
  const seenFacts = JSON.parse(localStorage.getItem(seenKey) || '[]');
  
  // Find unseen facts
  const unseenFacts = facts.filter(f => !seenFacts.includes(f.id));
  
  // If all facts have been seen, reset and start over
  if (unseenFacts.length === 0) {
    localStorage.setItem(seenKey, '[]');
    return facts[Math.floor(Math.random() * facts.length)];
  }
  
  // Get random unseen fact and mark as seen
  const fact = unseenFacts[Math.floor(Math.random() * unseenFacts.length)];
  seenFacts.push(fact.id);
  localStorage.setItem(seenKey, JSON.stringify(seenFacts));
  
  return fact;
};
