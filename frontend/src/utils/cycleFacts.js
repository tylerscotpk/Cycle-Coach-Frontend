/**
 * Get a random fact for a specific phase
 * @param {string} phase - Current cycle phase
 * @returns {Object} Random fact object
 */
export const getRandomFact = (phase) => {
  // Map phase names to our database keys
  const phaseMap = {
    'Menstrual': 'Menstrual',
    'Follicular': 'Follicular',
    'Ovulation': 'Ovulation',
    'Early Luteal': 'Early Luteal',
    'Late Luteal': 'Late Luteal/PMS',
    'Late Luteal/PMS': 'Late Luteal/PMS',
    'PMS': 'Late Luteal/PMS'
  };

  const mappedPhase = phaseMap[phase] || 'General';
  const facts = CYCLE_FACTS[mappedPhase] || CYCLE_FACTS.General;
  
  // Return a random fact from the phase
  const randomIndex = Math.floor(Math.random() * facts.length);
  return facts[randomIndex];
};

